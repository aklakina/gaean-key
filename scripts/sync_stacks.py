#!/usr/bin/env python3
"""Write the Terramate stacks of Gaean Key from the YAML configurations.

Terramate stack blocks (ids, ordering, inputs/outputs) must be static, so this script turns
`configurations/` into stack directories under `stacks/`:

  configurations/<service>/get/<id>.yml          -> stacks/<service>/get/<id>/            (one credential)
  configurations/<service>/rotation/<id>.yml     -> stacks/<service>/rotation/<id>/       (one credential)
  configurations/<service>/deployment/<unit>/**  -> stacks/<service>/deployment/<unit>/   (one deployment unit)

Each stack.tm.hcl declares which extension component it runs (`globals "gaean"`), exports its
credential (`output` block, producers) and imports the credentials its configs reference
(`input` blocks, wired to the producer stacks through Terramate outputs sharing). The OpenTofu
code itself is generated afterwards by `terramate generate` (templates in stacks/engine.tm.hcl).

Usage (from the repo root):
  python scripts/sync_stacks.py            write/update the stacks, report orphans
  python scripts/sync_stacks.py --check    exit 1 if stacks are out of date (CI)
  python scripts/sync_stacks.py --prune    also delete orphaned stacks (destroy them first!)

Requires PyYAML.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

import yaml

MARKER = "# Generated by scripts/sync_stacks.py from configurations/. Do not edit; rerun the script."
STACK_FILE = "stack.tm.hcl"
GENERATED_MARKER = "TERRAMATE: GENERATED AUTOMATICALLY"
PRODUCER_STAGES = ("get", "rotation")
STAGES = PRODUCER_STAGES + ("deployment",)
CONFIG_VAR_NAMES = ("configurations", "configs", "configuration")
OUTPUT_NAMES = ("secret", "secrets")
# Provided by the engine itself (stacks/engine.tm.hcl), no producer stack.
PLACEHOLDERS = {("none", "none"), ("TBD", "TBD")}
SHARING_BACKEND = "gaean"
EXTENSION_HOOK = "gaean.tm.hcl"
# Extension component folders serving each configuration stage, in order of preference. A Store
# (storing credentials in a credential manager) is wired exactly like a Deployment.
COMPONENT_DIRS = {"deployment": ("deployment", "store")}
# Value a consumer gets for a producer without state when run with --mock-on-fail (planning a fresh
# setup). gaean_mock marks it, so the generated code warns when planning with it and refuses to
# apply it (terraform_data.mock_guard in stacks/engine.tm.hcl).
MOCK = {"username": "mock", "secret": "mock", "gaean_mock": True}


class SyncError(Exception):
    pass


@dataclass
class Extension:
    path: str  # repo-relative
    config_var: str
    accepts_secrets: bool
    output_name: str | None
    has_hook: bool


@dataclass
class Unit:
    stage: str
    service: str
    id: str
    config_files: list[str]
    service_files: list[str]
    extension: Extension
    # (service, id) -> files referencing it
    refs: dict[tuple[str, str], list[str]] = field(default_factory=dict)
    deployment_files: list[dict] = field(default_factory=list)

    @property
    def key(self) -> str:
        return f"{self.service}/{self.stage}/{self.id}"

    @property
    def stack_dir(self) -> str:
        return f"stacks/{self.service}/{self.stage}/{self.id}"

    @property
    def stack_id(self) -> str:
        return stack_id(self.stage, self.service, self.id)


def _sanitize(value: str, allowed: str = r"A-Za-z0-9_-") -> str:
    return re.sub(rf"[^{allowed}]", "_", value)


def _hash(value: str, length: int = 8) -> str:
    return hashlib.sha1(value.encode("utf-8")).hexdigest()[:length]


def stack_id(stage: str, service: str, unit_id: str) -> str:
    """Terramate stack ids allow [A-Za-z0-9_-] and at most 64 characters."""
    readable = _sanitize(f"{stage}-{service}-{unit_id.replace('/', '-')}")[:55]
    return f"{readable}-{_hash(f'{stage}/{service}/{unit_id}')}"


def input_name(service: str, secret_id: str) -> str:
    """Name of the input block / OpenTofu variable carrying a referenced credential."""
    readable = _sanitize(f"{service}_{secret_id.replace('/', '_')}", r"A-Za-z0-9_")[:48]
    return f"cred_{readable}_{_hash(f'{service}/{secret_id}', 6)}"


def tag(value: str) -> str:
    tagged = re.sub(r"[^a-z0-9_-]", "_", value.lower()).strip("_-")
    return tagged or "_"


def _align(pairs: list[tuple[str, str]], pad: str) -> str:
    """Render `key = value` lines aligned like `terramate fmt` (hclwrite): consecutive single-line
    attributes are aligned, a multi-line value is not padded and ends the group."""
    lines = []
    group: list[tuple[str, str]] = []

    def flush():
        width = max((len(k) for k, _ in group), default=0)
        lines.extend(f"{pad}{k.ljust(width)} = {v}\n" for k, v in group)
        group.clear()

    for key, value in pairs:
        if "\n" in value:
            flush()
            lines.append(f"{pad}{key} = {value}\n")
        else:
            group.append((key, value))
    flush()
    return "".join(lines)


def hcl(value, indent: int = 0) -> str:
    """Render a JSON-like Python value as HCL."""
    pad = "  " * indent
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    if isinstance(value, str):
        # json escaping is valid HCL; additionally escape template sequences
        return json.dumps(value).replace("${", "$${").replace("%{", "%%{")
    if isinstance(value, (list, tuple)):
        if not value:
            return "[]"
        items = "".join(f"{pad}  {hcl(v, indent + 1)},\n" for v in value)
        return f"[\n{items}{pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = _align([(json.dumps(str(k)), hcl(v, indent + 1)) for k, v in value.items()], pad + "  ")
        return f"{{\n{items}{pad}}}"
    raise TypeError(f"cannot render {type(value)} as HCL")


def _block(header: str, attrs: dict) -> str:
    return _raw_block(header, [(k, hcl(v, 1)) for k, v in attrs.items()])


def _raw_block(header: str, lines: list[tuple[str, str]]) -> str:
    return f"{header} {{\n{_align(lines, '  ')}}}\n"


def load_extension(root: Path, service: str, stage: str) -> Extension:
    candidates = COMPONENT_DIRS.get(stage, (stage,))
    component = next(
        (root / "extensions" / service / c for c in candidates if (root / "extensions" / service / c).is_dir()),
        None,
    )
    if component is None:
        expected = " or ".join(f"extensions/{service}/{c}/" for c in candidates)
        raise SyncError(f"configurations/{service}/{stage} exists but the extension component {expected} does not")
    rel = component.relative_to(root).as_posix()
    source = "\n".join(p.read_text(encoding="utf-8") for p in sorted(component.glob("*.tf")))
    variables = set(re.findall(r'^\s*variable\s+"([^"]+)"', source, re.MULTILINE))
    outputs = set(re.findall(r'^\s*output\s+"([^"]+)"', source, re.MULTILINE))

    config_var = next((v for v in CONFIG_VAR_NAMES if v in variables), None)
    if config_var is None:
        raise SyncError(f"{rel} declares none of the configuration variables {', '.join(CONFIG_VAR_NAMES)}")
    output_name = None
    if stage in PRODUCER_STAGES:
        output_name = next((o for o in OUTPUT_NAMES if o in outputs), None)
        if output_name is None:
            raise SyncError(f"{rel} declares none of the outputs {', '.join(OUTPUT_NAMES)}")
    accepts_secrets = "secrets" in variables
    if stage == "deployment" and not accepts_secrets:
        raise SyncError(f"{rel} is a deployment component but declares no `secrets` variable")
    return Extension(rel, config_var, accepts_secrets, output_name, (component / EXTENSION_HOOK).is_file())


def find_refs(value, nested: bool = False):
    """Yield (service, id) of every nested `{service, id}` mapping (secret: / ref: references)."""
    if isinstance(value, dict):
        if nested and isinstance(value.get("service"), str) and isinstance(value.get("id"), str):
            yield value["service"], value["id"]
        for child in value.values():
            yield from find_refs(child, True)
    elif isinstance(value, list):
        for child in value:
            yield from find_refs(child, True)


def _load_yaml(path: Path) -> dict:
    try:
        content = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as err:
        raise SyncError(f"{path}: invalid YAML: {err}") from err
    if content is None:
        return {}
    if not isinstance(content, dict):
        raise SyncError(f"{path}: a configuration must be a mapping")
    return content


def discover(root: Path) -> list[Unit]:
    config_root = root / "configurations"
    units: list[Unit] = []
    for service_dir in sorted(p for p in config_root.iterdir() if p.is_dir()):
        service = service_dir.name
        service_file = service_dir / "service.yml"
        service_files = [service_file.relative_to(root).as_posix()] if service_file.is_file() else []
        defaults = _load_yaml(service_file) if service_files else {}

        for stage in STAGES:
            stage_dir = service_dir / stage
            # Only *.yml is loaded; *.yml.old etc. are disabled configs.
            files = sorted(p for p in stage_dir.rglob("*.yml") if p.is_file()) if stage_dir.is_dir() else []
            if not files:
                continue
            extension = load_extension(root, service, stage)

            grouped: dict[str, list[Path]] = {}
            for f in files:
                rel = f.relative_to(stage_dir).as_posix()
                unit_id = rel[: -len(".yml")] if stage in PRODUCER_STAGES else rel.split("/")[0].removesuffix(".yml")
                grouped.setdefault(unit_id, []).append(f)

            for unit_id, unit_files in grouped.items():
                unit = Unit(
                    stage=stage,
                    service=service,
                    id=unit_id,
                    config_files=[f.relative_to(root).as_posix() for f in unit_files],
                    service_files=service_files,
                    extension=extension,
                )
                for f in unit_files:
                    content = {**defaults, **_load_yaml(f)}
                    rel_file = f.relative_to(root).as_posix()
                    if stage == "deployment" or extension.accepts_secrets:
                        for ref in find_refs(content):
                            unit.refs.setdefault(ref, []).append(rel_file)
                    if stage == "deployment":
                        segments = PurePosixPath(f.relative_to(stage_dir).as_posix()).parts
                        unit.deployment_files.append(
                            {
                                "path_segments": list(segments[:-1]),
                                "name": segments[-1][: -len(".yml")],
                                "file": rel_file,
                            }
                        )
                units.append(unit)
    return units


def resolve(units: list[Unit]) -> dict[tuple[str, str], Unit]:
    """Map every credential to its producer stack and validate the references."""
    producers: dict[tuple[str, str], Unit] = {}
    errors = []
    for unit in units:
        if unit.stage not in PRODUCER_STAGES:
            continue
        cred = (unit.service, unit.id)
        if cred in producers:
            other = producers[cred]
            errors.append(
                f"Conflict: credential {unit.service}/{unit.id} is produced by both "
                f"{other.config_files[0]} ({other.stage}) and {unit.config_files[0]} ({unit.stage}). "
                "A service/id can either be retrieved or rotated, not both."
            )
            continue
        if cred in PLACEHOLDERS:
            errors.append(f"{unit.config_files[0]}: {unit.service}/{unit.id} is reserved for the engine's placeholder")
        producers[cred] = unit

    for unit in units:
        for ref, files in unit.refs.items():
            if ref in PLACEHOLDERS:
                continue
            if ref not in producers:
                errors.append(f"{', '.join(sorted(set(files)))}: no get or rotation config produces {ref[0]}/{ref[1]}")
            elif producers[ref] is unit:
                errors.append(f"{unit.config_files[0]}: a credential cannot reference itself")
    if errors:
        raise SyncError("\n".join(errors))
    return producers


def render(unit: Unit, producers: dict[tuple[str, str], Unit]) -> str:
    refs = sorted(r for r in unit.refs if r not in PLACEHOLDERS)
    watch = ["/" + f for f in unit.service_files + unit.config_files]
    if unit.stage == "deployment":
        watch.append("/modules/config_processor.jinja2")

    gaean = {
        "stage": unit.stage,
        "service": unit.service,
        "id": unit.id,
        "extension": unit.extension.path,
        "config_var": unit.extension.config_var,
        "output_name": unit.extension.output_name,
        "pass_secrets": unit.extension.accepts_secrets,
        "service_files": unit.service_files,
        "config_files": unit.config_files,
    }
    if unit.stage == "deployment":
        gaean["deployment_files"] = unit.deployment_files
    gaean["secret_refs"] = {input_name(*ref): {"service": ref[0], "id": ref[1]} for ref in refs}

    kind = {"get": "Retrieved credential", "rotation": "Rotated credential", "deployment": "Deployment unit"}
    stack = {
        "name": unit.key,
        "description": f"{kind[unit.stage]} {unit.service}/{unit.id}",
        "id": unit.stack_id,
        "tags": ["gaean", unit.stage, f"svc_{tag(unit.service)}"],
    }
    if refs:
        # input blocks define the data flow but not the run order
        stack["after"] = sorted({"/" + producers[ref].stack_dir for ref in refs})
    stack["watch"] = watch
    parts = [
        MARKER + "\n",
        _block("stack", stack),
        _block('globals "gaean"', gaean),
    ]
    if unit.extension.has_hook:
        parts.append(_block("import", {"source": f"/{unit.extension.path}/{EXTENSION_HOOK}"}))
    if unit.stage in PRODUCER_STAGES:
        parts.append(
            _raw_block(
                'output "credential"',
                [
                    ("description", hcl(f"{unit.service}/{unit.id}: {{username, secret}} of the active credential")),
                    ("backend", hcl(SHARING_BACKEND)),
                    ("value", "local.credential"),
                    ("sensitive", "true"),
                ],
            )
        )
    for ref in refs:
        producer = producers[ref]
        parts.append(
            _raw_block(
                f'input "{input_name(*ref)}"',
                [
                    ("backend", hcl(SHARING_BACKEND)),
                    ("from_stack_id", hcl(producer.stack_id)),
                    ("value", "outputs.credential.value"),
                    ("sensitive", "true"),
                    ("mock", hcl(MOCK, 1)),
                ],
            )
        )
    return "\n".join(parts)


def managed_stacks(root: Path) -> set[str]:
    stacks_root = root / "stacks"
    if not stacks_root.is_dir():
        return set()
    managed = set()
    for f in stacks_root.rglob(STACK_FILE):
        with f.open(encoding="utf-8") as fh:
            if fh.readline().rstrip("\r\n") == MARKER:
                managed.add(f.parent.relative_to(root).as_posix())
    return managed


def _has_local_state(stack: Path) -> bool:
    state = stack / "terraform.tfstate"
    if not state.is_file():
        return False
    try:
        return bool(json.loads(state.read_text(encoding="utf-8")).get("resources"))
    except (ValueError, OSError):
        return True


def prune(root: Path, stack_rel: str) -> None:
    stack = root / stack_rel
    if _has_local_state(stack):
        raise SyncError(f"{stack_rel} still has resources in its local state; destroy them first")
    for item in stack.iterdir():
        if item.is_dir() and item.name == ".terraform":
            shutil.rmtree(item)
        elif item.is_file():
            generated = item.suffix == ".tf" and GENERATED_MARKER in item.read_text(encoding="utf-8").split("\n", 1)[0]
            if item.name in (STACK_FILE, ".terraform.lock.hcl", "terraform.tfstate", "terraform.tfstate.backup") or generated:
                item.unlink()
    # remove now-empty directories up to stacks/
    current = stack
    stacks_root = root / "stacks"
    while current != stacks_root and current.is_dir() and not any(current.iterdir()):
        current.rmdir()
        current = current.parent


def sync(root: Path, check: bool = False, do_prune: bool = False, out=sys.stdout) -> int:
    units = discover(root)
    producers = resolve(units)

    desired = {unit.stack_dir: render(unit, producers) for unit in units}
    changed = []
    for stack_rel, content in sorted(desired.items()):
        path = root / stack_rel / STACK_FILE
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current is not None and current.replace("\r\n", "\n") == content:
            continue
        changed.append(stack_rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        print(f"{'outdated' if check else 'wrote'}: {stack_rel}/{STACK_FILE}", file=out)

    orphans = sorted(managed_stacks(root) - set(desired))
    for orphan in orphans:
        if do_prune and not check:
            prune(root, orphan)
            print(f"pruned: {orphan}", file=out)
        else:
            print(
                f"orphan: {orphan} (its config is gone; destroy it with "
                f"`terramate run --chdir {orphan} -- tofu destroy`, then rerun with --prune)",
                file=out,
            )

    if check:
        if changed or orphans:
            print("Stacks are out of date: run `python scripts/sync_stacks.py` and `terramate generate`.", file=out)
            return 1
        print(f"{len(desired)} stacks up to date.", file=out)
        return 0
    if changed or (do_prune and orphans):
        print("Now run `terramate generate`.", file=out)
    else:
        print(f"{len(desired)} stacks up to date.", file=out)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent, help="repository root")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="only check, exit 1 if stacks are out of date")
    mode.add_argument("--prune", action="store_true", help="delete orphaned stacks (after destroying them)")
    args = parser.parse_args(argv)
    try:
        return sync(args.root.resolve(), check=args.check, do_prune=args.prune)
    except SyncError as err:
        print(f"error: {err}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
