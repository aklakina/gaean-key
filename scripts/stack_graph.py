#!/usr/bin/env python3
"""Render the Terramate stack graph of Gaean Key as a Mermaid diagram.

Runs `terramate experimental run-graph` (the stacks' run order as Graphviz DOT) and converts it to a
Mermaid flowchart that GitHub renders. Stacks are grouped per service and styled per stage, and every
edge is labelled with the credential the producer stack hands to its consumer.

Usage (from the repo root):
  python scripts/stack_graph.py                       print the Mermaid diagram
  python scripts/stack_graph.py --write docs/stacks.md  replace the block between the stack-graph markers
  python scripts/stack_graph.py --check docs/stacks.md  exit 1 if that block is out of date (CI)

Pass Terramate filters after `--`, e.g. `python scripts/stack_graph.py -- --tags rotation`.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

START = "<!-- stack-graph:start (generated by scripts/stack_graph.py, do not edit) -->"
END = "<!-- stack-graph:end -->"
STAGES = ("get", "rotation", "deployment")
STYLES = {
    "get": "fill:#e3f2fd,stroke:#1565c0",
    "rotation": "fill:#fff3e0,stroke:#ef6c00",
    "deployment": "fill:#e8f5e9,stroke:#2e7d32",
}


def run_graph(root: Path, extra: list[str]) -> str:
    cmd = ["terramate", "experimental", "run-graph", "--label", "stack.name", *extra]
    result = subprocess.run(cmd, cwd=root, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"`{' '.join(cmd)}` failed:\n{result.stderr}")
    return result.stdout


def parse_dot(dot: str) -> tuple[dict[str, str], list[tuple[str, str]]]:
    nodes = dict(re.findall(r'^\s*(\w+)\s*\[label="((?:[^"\\]|\\.)*)"\]', dot, re.MULTILINE))
    edges = re.findall(r"^\s*(\w+)\s*->\s*(\w+)", dot, re.MULTILINE)
    return nodes, edges


def to_mermaid(nodes: dict[str, str], edges: list[tuple[str, str]]) -> str:
    # Gaean Key stack names are "<service>/<stage>/<id>" (see scripts/sync_stacks.py).
    def split(name: str) -> tuple[str, str, str]:
        parts = name.split("/", 2)
        return (parts[0], parts[1], parts[2]) if len(parts) == 3 and parts[1] in STAGES else ("other", "", name)

    def esc(text: str) -> str:
        return text.replace('"', "#quot;").replace("<", "#lt;").replace(">", "#gt;")

    lines = ["flowchart LR"]
    by_service: dict[str, list[str]] = {}
    for node, name in sorted(nodes.items(), key=lambda kv: kv[1]):
        by_service.setdefault(split(name)[0], []).append(node)
    for index, (service, members) in enumerate(sorted(by_service.items())):
        lines.append(f'    subgraph svc{index}["{esc(service)}"]')
        lines.append("        direction TB")
        for node in members:
            _, stage, unit = split(nodes[node])
            label = f"{stage}: {unit}" if stage else unit
            lines.append(f'        {node}["{esc(label)}"]:::{stage or "other"}')
        lines.append("    end")

    for producer, consumer in sorted(edges, key=lambda e: (nodes.get(e[0], ""), nodes.get(e[1], ""))):
        service, stage, unit = split(nodes.get(producer, producer))
        # an edge from a get/rotation stack carries that stack's credential
        if stage in ("get", "rotation"):
            lines.append(f'    {producer} -- "{esc(f"{service}/{unit}")}" --> {consumer}')
        else:
            lines.append(f"    {producer} --> {consumer}")

    for stage, style in STYLES.items():
        lines.append(f"    classDef {stage} {style}")
    lines.append("    classDef other fill:#eeeeee,stroke:#616161")
    return "\n".join(lines) + "\n"


def block(diagram: str) -> str:
    return f"{START}\n```mermaid\n{diagram}```\n{END}"


def replace_block(text: str, diagram: str, path: Path) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        sys.exit(f"{path}: no stack-graph markers found (add {START!r} ... {END!r})")
    return pattern.sub(lambda _: block(diagram), text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent, help="repository root")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", type=Path, metavar="MD", help="update the marked block in this markdown file")
    mode.add_argument("--check", type=Path, metavar="MD", help="exit 1 if the marked block is out of date")
    parser.add_argument("terramate_args", nargs="*", help="extra arguments for terramate (after --)")
    args = parser.parse_args(argv)

    diagram = to_mermaid(*parse_dot(run_graph(args.root, args.terramate_args)))
    target = args.write or args.check
    if target is None:
        sys.stdout.write(diagram)
        return 0

    path = target if target.is_absolute() else args.root / target
    current = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    updated = replace_block(current, diagram, path)
    if args.check:
        if updated != current:
            print(f"{target}: stack graph is out of date, run `python scripts/stack_graph.py --write {target}`")
            return 1
        print(f"{target}: stack graph up to date")
        return 0
    if updated != current:
        path.write_text(updated, encoding="utf-8", newline="\n")
        print(f"updated {target}")
    else:
        print(f"{target}: stack graph up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
